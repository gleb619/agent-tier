import { existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { writeFileAtomicSync } from "../atomic-write";
import { KANBAN_COMPOSE_DOC } from "./compose-doc";

export type LoopFileOutcome = "created" | "unchanged" | "skipped";

export interface LoopFileResult {
  outcome: LoopFileOutcome;
  file: string;
  /** Set when outcome is "skipped": why the file could not be written. */
  reason?: string;
}

export interface LoopTextOptions {
  /** Board path as the agent should type it (e.g. `docs/kanban.md`). */
  board?: string;
  /** Checks the loop runs; editable in the generated file. */
  lintCmd?: string;
  testCmd?: string;
}

const DEFAULT_BOARD = "docs/kanban.md";
const DEFAULT_LINT_CMD = "pnpm exec biome ci . && npx tsc --noEmit";
const DEFAULT_TEST_CMD = "npx vitest run";

/** `docs/kanban.md` -> `docs/kanban-loop.md`; the loop file always sits next to its board. */
export function loopFilePath(boardFile: string): string {
  return siblingPath(boardFile, "loop");
}

function siblingPath(boardFile: string, suffix: string): string {
  const ext = path.extname(boardFile);
  return path.join(path.dirname(boardFile), `${path.basename(boardFile, ext)}-${suffix}${ext || ".md"}`);
}

/** `docs/kanban.md` -> `docs/kanban-compose.md`: the time/plan-file/compose reference the board links to. */
export function composeFilePath(boardFile: string): string {
  return siblingPath(boardFile, "compose");
}

/**
 * Self-contained, independent `/loop` prompt for a kanban board. Same shape as the repo's
 * LOOP.md (skills, rules, state machine, safety) but the work source is the board and the
 * writer is `at compose`; nothing here is hand-edited code.
 */
export function kanbanLoopText(opts: LoopTextOptions = {}): string {
  const board = opts.board ?? DEFAULT_BOARD;
  const lintCmd = opts.lintCmd ?? DEFAULT_LINT_CMD;
  const testCmd = opts.testCmd ?? DEFAULT_TEST_CMD;
  const boardFlag = board === DEFAULT_BOARD ? "" : ` --board ${board}`;
  return `# Kanban Loop

\`/loop 30m ${loopFilePath(board)}\`

State-machine prompt for an agent that works the kanban board \`${board}\` through the \`at\` CLI
(\`at kanban\` + \`at compose\`). It never edits the board or code by hand. Cycle:
**check → lint → poll → prepare → run → review → report**. When the board is drained the loop
stops: crons are cancelled and the agent exits. Generated by \`at kanban init\` / \`at kanban loop\`; edit freely,
it is never overwritten (\`at kanban loop --force\` regenerates it).

Feed this file as the prompt on every tick. One tick = advance the machine to a tick boundary (⏸), end the turn.
Board, statuses, plan files and compose: [${path.basename(board)}](${path.basename(board)}), [${path.basename(composeFilePath(board))}](${path.basename(composeFilePath(board))}).

## Commands

Substitute these wherever the prompt says \`<LINT>\` / \`<TEST>\`:

| Name   | Command |
| ------ | ------- |
| \`LINT\` | \`${lintCmd}\` |
| \`TEST\` | \`${testCmd}\` |

## Required Skills

Invoke before any work:

- \`caveman\` — compressed communication throughout all sessions
- \`codegraph\` — codebase exploration; never grep when \`codegraph_*\` tools are available
- \`delegate-with-at\` — delegate code writing to subagents via the \`at\` CLI

## Rules

- Never edit the board or code by hand. Board changes only via \`at kanban\`; code only via \`at compose\`.
- Never \`git push\`, \`git stash\`, \`git reset\`, or edit \`~/.at/*\` by hand.
- One \`at compose\` job at a time (job name \`loop\`). No plan-then-do.
- Every task runs in its own worktree + branch (\`--worktree\`), merged to main only after the test gate (\`--merge\`).
  No \`Co-Authored-By\` / AI trailers in commits.
- You are not alone: touch only what the task needs, ignore unrelated failures.
- Caveman/ultra-brief reports. Minimal texting, save tokens.

## State machine

\`\`\`
CHECK ─► LINT ─► POLL ─► PREPARE ─► RUN ─► REVIEW ─► REPORT ─► ⏸
  │ job running  │ violations │ drained
  ▼ ⏸ one line   ▼ STOP       ▼ STOP
\`\`\`

### State: CHECK

\`at compose jobs\`. Job \`loop\` \`running\` → \`at compose logs loop -n 20\`, report one line, ⏸ end tick.
Never start a second job. Otherwise → **LINT**.

### State: LINT

\`at kanban lint${boardFlag}\`. Violations → report them verbatim, **STOP** (\`LOOP: BOARD INVALID\`). Else → **POLL**.

### State: POLL

\`at kanban next${boardFlag}\`. Prints \`No executable task found.\` → **STOP** (\`LOOP: BOARD DRAINED\`).
Else note the task \`ID\` → **PREPARE**.

### State: PREPARE

A task needs a plan file with \`## Keywords\` and a \`## Time\` section (\`Planned\`) before compose can use it.
Check \`at kanban show <ID> --with-plan\`. Missing → \`at kanban add --id <ID> --keywords "<symbols, paths>"\`,
have the planner agent fill \`Planned: <duration>\`, then \`at kanban estimate <ID>\`. Then → **RUN**.

### State: RUN

Start one detached job:

\`\`\`bash
at compose --loop --worktree --merge --max-tasks 3 --stop-on-fail \\
  --test-cmd '<TEST>' --background --name loop${boardFlag}
\`\`\`

⏸ end tick. The job works up to 3 tasks (claim → implement → test gate → merge); the next tick enters **CHECK**.

### State: REVIEW

Entered on a tick where \`at compose jobs\` shows \`loop\` exited. \`at kanban list${boardFlag}\`:

- Row \`Blocked\`: read \`~/.at/compose/<id lowercase>/outcome.md\`, report the cause. Retry at most once
  (\`at kanban status <ID> Backlog\`), second block → leave it for a human.
- Row newly \`Done\`: on main run \`<LINT>\` and \`<TEST>\`. Failure →
  \`at feedback add -k bug "<ID> broke main: <output tail>"\`, **STOP** (\`LOOP: MAIN BROKEN\`).

Then → **REPORT**.

### State: REPORT

Print at most 5 lines: tasks Done / Blocked / running, time consumed vs planned (Run Details / \`at bridge usage summary\`).
Then → **POLL** (new work) or ⏸.

### State: STOP

Terminal. Print one signal: \`LOOP: BOARD DRAINED\`, \`LOOP: BOARD INVALID\`, \`LOOP: MAIN BROKEN\`.

1. \`CronList\`, then \`CronDelete\` every job whose prompt references this file.
2. In dynamic mode, \`ScheduleWakeup\` with \`stop: true\`. Never schedule another wakeup or \`CronCreate\`.
3. Print \`loop stopped — <signal>, removed cron ids: <ids|none>\` and end the turn.
   A fixed-interval \`/loop 30m\` owned by the harness cannot be stopped from inside; tell the user to cancel it.

Resume by restarting \`/loop\` after new tasks are added.

## Safety

- Cheap by design: a drained board costs no agent runs, a tick that finds a running job only reads its log.
- Max 3 tasks per job (\`--max-tasks\`); \`--stop-on-fail\` halts at the first failed run.
- Stop the job: \`at compose stop loop\` (finishes the in-flight task; resumable).
- Run heavy work only via \`scripts/at-safe.sh\` when present; one delegated task at a time.
- Without an agent: \`at compose --loop --worktree --merge --follow 60 --max-tasks 20 --background\` polls in one process.
`;
}

function ensureDoc(file: string, text: string, force?: boolean): LoopFileResult {
  try {
    if (existsSync(file) && !force) return { outcome: "unchanged", file };
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileAtomicSync(file, text);
    return { outcome: "created", file };
  } catch (err) {
    return { outcome: "skipped", file, reason: (err as Error).message };
  }
}

/**
 * Create the loop prompt next to `boardFile` when it is missing. Never overwrites (unless `force`)
 * and never throws: an unwritable directory yields `skipped` with a reason, so board commands keep working.
 */
export function ensureLoopFile(boardFile: string, opts: LoopTextOptions & { force?: boolean } = {}): LoopFileResult {
  return ensureDoc(loopFilePath(boardFile), kanbanLoopText(opts), opts.force);
}

/** Same contract as {@link ensureLoopFile} for the compose reference doc. */
export function ensureComposeFile(boardFile: string, opts: { force?: boolean } = {}): LoopFileResult {
  return ensureDoc(composeFilePath(boardFile), KANBAN_COMPOSE_DOC, opts.force);
}
